set_font(doc.styles["List Bullet"], 10)
set_font(doc.styles["Caption"], 8.5, False, RGBColor(0x6B, 0x60, 0x55))

def p(text="", bold_prefix=None, size=None, italic=False):
    para = doc.add_paragraph()
    if bold_prefix:
        r = para.add_run(bold_prefix); r.bold = True
    r = para.add_run(text); r.italic = italic
    if size: r.font.size = Pt(size)
    return para

def bullet(text, bold_prefix=None):
    para = doc.add_paragraph(style="List Bullet")
    if bold_prefix:
        r = para.add_run(bold_prefix); r.bold = True
    para.add_run(text)
    return para

def shade(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)

def table(header, rows, widths):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, text in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(text); r.bold = True; r.font.size = Pt(9)
        shade(c, "F3E6D8")
    for row in rows:
        cells = t.add_row().cells
        for i, text in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(text)); r.font.size = Pt(9)
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    for i, w in enumerate(widths):
        t.columns[i].width = Cm(w)
    layout = OxmlElement("w:tblLayout"); layout.set(qn("w:type"), "fixed"); t._tbl.tblPr.append(layout)
    doc.add_paragraph()
    return t

def caption(text):
    para = doc.add_paragraph(style="Caption"); para.add_run(text)

def frames(name, title=None):
    """High quality, then the real app pixels on a Retina MacBook (2x) and a normal monitor (1x)."""
    if title: doc.add_paragraph().add_run(title).bold = True
